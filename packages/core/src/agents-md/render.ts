import { PRODUCT_NAME, CLI_BINARY } from '../constants.js';
import type { Config } from '../schemas/config.js';
import type { StackProfile } from '../schemas/stack-profile.js';

/**
 * Render the managed AGENTS.md block.
 *
 * Source of truth: run.md §9.1.
 *
 * Rules:
 *   - Keep the block short (< 150 lines, run.md §9.1).
 *   - Include: stack summary, workflow contract, always-on core rules,
 *     pointers for task-scoped rules.
 *   - No agent-specific content — this is read by every agent (§22.3 "core
 *     has no knowledge of any specific agent").
 */

/** Cheap token estimate: ~4 chars per token in English prose. Good enough for
 *  budget guards; the real tokeniser lives in the agent, not here. */
export function estimateTokens(text: string): number {
  return Math.ceil(text.length / 4);
}

export const MAX_AGENTS_MD_TOKENS = 1500;
export const MAX_AGENTS_MD_LINES = 150;

export class AgentsBlockBudgetError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'AgentsBlockBudgetError';
  }
}

function fmtList(values: readonly string[]): string {
  if (values.length === 0) return '_(none detected)_';
  return values.map((v) => `\`${v}\``).join(', ');
}

export interface RenderOptions {
  /** Override the default budget guard (for tests). */
  readonly maxTokens?: number;
  readonly maxLines?: number;
}

/**
 * Produce the managed-block body (what goes BETWEEN the markers — the writer
 * adds the markers itself).
 */
export function renderAgentsBlock(
  profile: StackProfile,
  config: Config,
  options: RenderOptions = {},
): string {
  const maxTokens = options.maxTokens ?? MAX_AGENTS_MD_TOKENS;
  const maxLines = options.maxLines ?? MAX_AGENTS_MD_LINES;

  const stackSummary = [
    `- **Languages:** ${fmtList(profile.languages.values)}`,
    `- **Frameworks:** ${fmtList(profile.frameworks.values)}`,
    `- **Package managers:** ${fmtList(profile.packageManagers.values)}`,
    `- **Test runners:** ${fmtList(profile.testRunners.values)}`,
    `- **Linters:** ${fmtList(profile.linters.values)}`,
    `- **CI:** ${profile.ciProvider.value ? `\`${profile.ciProvider.value}\`` : '_(none detected)_'}`,
  ].join('\n');

  const body = [
    `## ${PRODUCT_NAME} (managed section — do not hand-edit)`,
    '',
    `${PRODUCT_NAME} verifies that AI-generated code matches the project's spec and`,
    'rules. Content outside this block is yours; content inside is regenerated by',
    `\`${CLI_BINARY} init\` / \`${CLI_BINARY} update\`.`,
    '',
    '### Project stack',
    stackSummary,
    '',
    '### Workflow contract',
    `For every task you work on, follow these four steps in order:`,
    '',
    `1. **Read the spec.** Open the active \`.specgate/specs/*/requirements.md\` and`,
    `   \`tasks.md\`. Confirm which acceptance criterion (AC-xxx.y) you are`,
    `   implementing.`,
    `2. **Pull task-scoped rules.** Run \`${CLI_BINARY} context --task <T-id>\` (or`,
    `   call \`get_task_context\` over MCP). Do NOT read every rule file by hand —`,
    `   the context tool enforces a token budget and ranks by relevance.`,
    `3. **Implement.** Keep logic in the layer the rules describe. Write a test`,
    `   that references the AC id (e.g. \`it("AC-001.1: ...")\`).`,
    `4. **Verify.** Run \`${CLI_BINARY} check\` before claiming done. If it fails,`,
    `   fix only what the report lists; do NOT disable gates or edit`,
    `   \`.specgate/config.yaml\` to make it pass (run.md §13.3).`,
    '',
    '### Always-on rules',
    '- Never commit secrets. Reference env vars; add placeholders to `.env.example`.',
    '- No shell string interpolation in subprocess calls; use argument arrays.',
    `- Changes must trace to a REQ/AC id. Include \`Spec: REQ-xxx\` in commit`,
    `  trailers once this repo is on \`strictness: standard\` or higher.`,
    `- When you touch a shared file (this file, CI config, hooks), only modify`,
    `  bytes inside \`<!-- specgate:begin -->\` / \`<!-- specgate:end -->\` markers.`,
    '',
    '### Current enforcement',
    `- Strictness: **${config.strictness}**`,
    `- Enabled gates: ${listEnabledGates(config)}`,
    `- Fix-loop max attempts: ${config.fix_loop.max_attempts}`,
    `- Rule-context token budget: ${config.context.max_rule_tokens}`,
  ].join('\n');

  const lines = body.split('\n').length;
  const tokens = estimateTokens(body);
  if (lines > maxLines) {
    throw new AgentsBlockBudgetError(
      `AGENTS.md block exceeds the ${maxLines}-line budget (actual ${lines}).`,
    );
  }
  if (tokens > maxTokens) {
    throw new AgentsBlockBudgetError(
      `AGENTS.md block exceeds the ${maxTokens}-token budget (actual ${tokens}).`,
    );
  }
  return body;
}

function listEnabledGates(config: Config): string {
  const names: string[] = [];
  for (const [name, g] of Object.entries(config.gates)) {
    if (g.enabled) names.push(name);
  }
  return names.length === 0 ? '_(none)_' : names.map((n) => `\`${n}\``).join(', ');
}
